package mix.client.mixui.integration.haunt.standalone;

import mix.client.mixui.integration.haunt.standalone.proxy.CommonProxy;
import net.minecraftforge.fml.common.Mod;
import net.minecraftforge.fml.common.SidedProxy;
import net.minecraftforge.fml.common.Mod.EventHandler;
import net.minecraftforge.fml.common.event.FMLInitializationEvent;
import net.minecraftforge.fml.common.event.FMLPreInitializationEvent;

@Mod(
   modid = "hauntvisuals",
   name = "HAUN\'T VISUALS",
   version = "2.0.0",
   clientSideOnly = true,
   acceptedMinecraftVersions = "[1.8.9]"
)
public final class FuriahVisualsMod {
   public static final String MOD_ID = "hauntvisuals";
   public static final String NAME = "HAUN\'T VISUALS";
   public static final String VERSION = "2.0.0";
   @SidedProxy(
      clientSide = "mix.client.mixui.integration.haunt.standalone.proxy.ClientProxy",
      serverSide = "mix.client.mixui.integration.haunt.standalone.proxy.CommonProxy"
   )
   public static CommonProxy proxy;

   @EventHandler
   public void preInit(FMLPreInitializationEvent event) {
      event.getModMetadata().autogenerated = false;
      event.getModMetadata().name = "HAUN\'T VISUALS";
      event.getModMetadata().version = "2.0.0";
      event.getModMetadata().description = "A DARKER WAY TO SEE MINECRAFT. Visual effects, weapons, skies and interface for Minecraft 1.8.9.";
   }

   @EventHandler
   public void init(FMLInitializationEvent event) {
      proxy.initialize();
   }
}
