package mix.client.mixui.discord;

import java.time.OffsetDateTime;

import mix.client.mixui.Mix;
import mix.client.mixui.discord.ipc.IPCClient;
import mix.client.mixui.discord.ipc.IPCListener;
import mix.client.mixui.discord.ipc.entities.RichPresence;
import mix.client.mixui.discord.ipc.exceptions.NoDiscordClientException;

public class DiscordRPC {

	private IPCClient client;
	
	public void start() {
		
		client = new IPCClient(1059341815205068901L);
		client.setListener(new IPCListener() {
			@Override
			public void onReady(IPCClient client) {
				
				RichPresence.Builder builder = new RichPresence.Builder();
				
				builder.setState("Playing Mix Client " + Mix.getInstance().getVersion())
						.setStartTimestamp(OffsetDateTime.now())
						.setLargeImage("icon");
				
				client.sendRichPresence(builder.build());
			}
		});
		
		try {
			client.connect();
		} catch (NoDiscordClientException e) {
			e.printStackTrace();
		}
	}
	
	public void stop() {
		client.close();
	}

	public IPCClient getClient() {
		return client;
	}
	
	public boolean isStarted() {
		return client != null;
	}
}
